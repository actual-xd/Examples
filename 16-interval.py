# Алгоритм вычисления функции F(n):
# F(0) = 0
# F(n) = F(n-1) + n
# Отсюда F(n) = n * (n + 1) // 2
#
# F(n) не делится на 3 тогда и только тогда, когда n * (n + 1) // 2 не кратно 3.
# Так как n * (n + 1) всегда чётно, F(n) % 3 != 0 равносильно тому,
# что n * (n + 1) не делится на 6, т.е. не делится на 3.
# Произведение n * (n + 1) не делится на 3, если ни n, ни n+1 не кратны 3,
# а это выполняется только при n ≡ 1 (mod 3).

A = 765432010
B = 1542613234

# Ищем первое число в [A, B], дающее остаток 1 при делении на 3
first = A + ((1 - A) % 3)

if first > B:
    count = 0
else:
    count = (B - first) // 3 + 1

print(count)  # Вывод: 259060409
