"""
ЗАНЯТИЕ 1: ОСНОВЫ PYGAME
Время: 60 минут

Цель: создать окно, нарисовать сетку, реагировать на клик мыши

🎯 К концу урока ученик увидит:
- Окно 800×600 пикселей
- Зелёную сетку (как шахматная доска)
- Красный квадратик где кликнул мышью
"""

import pygame
import sys

# ============================================
# 1. ИНИЦИАЛИЗАЦИЯ PYGAME
# ============================================
pygame.init()

# ============================================
# 2. НАСТРОЙКИ ИГРЫ
# ============================================

# Размер окна в пикселях
WIDTH = 800
HEIGHT = 600

# Частота обновления (FPS = кадры в секунду)
FPS = 60

# Размер одной клетки сетки
CELL = 40

# ============================================
# 3. ЦВЕТА (RGB ФОРМАТ)
# ============================================
# RGB = (Red, Green, Blue) - значения от 0 до 255

WHITE = (255, 255, 255)      # Белый
BLACK = (0, 0, 0)            # Чёрный
GREEN = (50, 150, 50)        # Зелёный (для травы)
DARK_GREEN = (30, 100, 30)   # Тёмный зелёный (для сетки)
RED = (255, 100, 100)        # Красный (для маркера клика)

# ============================================
# 4. СОЗДАНИЕ ОКНА
# ============================================
screen = pygame.display.set_mode((WIDTH, HEIGHT))
pygame.display.set_caption("Tower Defence - Занятие 1")

# ============================================
# 5. ЧАСЫ ДЛЯ КОНТРОЛЯ FPS
# ============================================
clock = pygame.time.Clock()

# ============================================
# 6. ПЕРЕМЕННЫЕ ИГРЫ
# ============================================
click_pos = None  # Последняя позиция клика мыши
running = True    # Флаг работы программы

# ============================================
# 7. ГЛАВНЫЙ ЦИКЛ ИГРЫ
# ============================================

while running:
    # Ограничиваем FPS (60 кадров в секунду)
    clock.tick(FPS)

    # ========== СОБЫТИЕ ==========
    # Проверяем что произошло (клик, нажатие клавиши, закрытие окна)

    for event in pygame.event.get():

        # Если нажали кнопку "закрыть окно"
        if event.type == pygame.QUIT:
            running = False
            print("Окно закрыто!")

        # Если произошёл клик мыши
        if event.type == pygame.MOUSEBUTTONDOWN:
            click_pos = event.pos  # Сохраняем координаты клика
            print(f"Клик мыши! Позиция: {click_pos}")

            # event.button:
            # 1 = левая кнопка
            # 2 = средняя кнопка (колёсико)
            # 3 = правая кнопка

    # ========== ОБНОВЛЕНИЕ ==========
    # Обновляем логику игры
    # (пока здесь ничего не меняется, будет на следующих уроках)

    # ========== РИСОВАНИЕ ==========

    # 1. Заполняем весь экран зелёным цветом
    screen.fill(GREEN)

    # 2. Рисуем вертикальные линии сетки
    for x in range(0, WIDTH, CELL):
        # pygame.draw.line(surface, color, start_pos, end_pos, width)
        pygame.draw.line(screen, DARK_GREEN, (x, 0), (x, HEIGHT), 1)

    # 3. Рисуем горизонтальные линии сетки
    for y in range(0, HEIGHT, CELL):
        pygame.draw.line(screen, DARK_GREEN, (0, y), (WIDTH, y), 1)

    # 4. Если был клик - рисуем красный квадратик в том месте
    if click_pos:
        # pygame.draw.rect(surface, color, rect)
        # Rect: (левая координата, верхняя координата, ширина, высота)
        x, y = click_pos
        pygame.draw.rect(screen, RED, (x - 15, y - 15, 30, 30))

    # 5. Обновляем экран (показываем то что нарисовали)
    pygame.display.flip()

# ============================================
# 8. ВЫХОД ИЗ ПРОГРАММЫ
# ============================================
pygame.quit()
sys.exit()

print("Программа завершена!")

